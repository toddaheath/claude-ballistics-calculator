    public static double GetDragCoefficient(double mach)
    {
        if (mach <= 0)
            return DragTable[0].Cd;

        if (mach >= DragTable[^1].Mach)
            return DragTable[^1].Cd;

        // Find the bracketing entries and interpolate
        for (int i = 1; i < DragTable.Length; i++)
        {
            if (mach <= DragTable[i].Mach)
            {
                var lower = DragTable[i - 1];
                var upper = DragTable[i];
                double fraction = (mach - lower.Mach) / (upper.Mach - lower.Mach);
                return lower.Cd + fraction * (upper.Cd - lower.Cd);
            }
        }

        return DragTable[^1].Cd;
    }
